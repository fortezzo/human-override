// Writes CREDITS.md and the in-game credits list from the asset manifest,
// so the two can never drift apart from what the game actually ships.
//
// Only assets that are really used are listed: for sounds that means the
// packs referenced in audio-spec.mjs, for guns the ones marked `shipped`.

import fs from 'node:fs';
import path from 'node:path';
import { AUDIO_SPEC } from './audio-spec.mjs';
import { AMBIENTCG, DOWNLOAD_DIR, FONTS, KENNEY, OPENGAMEART, POLYHAVEN_HDRIS, POLYHAVEN_MODELS, POLYHAVEN_TEXTURES, SKETCHFAB } from './manifest.mjs';

const LICENSE_URL = {
  CC0: 'https://creativecommons.org/publicdomain/zero/1.0/',
  'CC-BY 3.0': 'https://creativecommons.org/licenses/by/3.0/',
  'CC-BY 4.0': 'https://creativecommons.org/licenses/by/4.0/',
  'OFL 1.1': 'https://openfontlicense.org/',
};

function polyhaven(id) {
  const file = path.join(DOWNLOAD_DIR, 'polyhaven', '_api', `${id}.info.json`);
  if (!fs.existsSync(file)) throw new Error(`Missing Poly Haven info for ${id}; run tools/assets/fetch.mjs first.`);
  const info = JSON.parse(fs.readFileSync(file, 'utf8'));
  return { title: info.name, author: Object.keys(info.authors).join(', '), url: `https://polyhaven.com/a/${id}`, license: 'CC0' };
}

const usedPacks = new Set(AUDIO_SPEC.flatMap((s) => s.layers.map((l) => l.pack)));

/** @type {{ title: string, note?: string, items: { title: string, author: string, url: string, license: string, note?: string }[] }[]} */
const groups = [
  {
    title: 'Robot character and animations',
    note: 'Used under the Adobe Mixamo terms. The game ships only a converted, simplified and re-skinned version; the original files are not redistributed.',
    items: [
      { title: 'Y Bot character', author: 'Adobe Mixamo', url: 'https://www.mixamo.com/', license: 'Mixamo' },
      { title: 'Animations: Zombie Idle, Zombie Walk, Zombie Running, Zombie Punching, Zombie Reaction Hit, Death, Death From The Front', author: 'Adobe Mixamo', url: 'https://www.mixamo.com/', license: 'Mixamo' },
    ],
  },
  {
    title: 'Weapons',
    items: SKETCHFAB.filter((g) => g.shipped).map((g) => ({ title: g.title, author: g.author, url: g.page, license: g.license, note: g.changes })),
  },
  { title: 'Props and fixtures', items: POLYHAVEN_MODELS.map((m) => polyhaven(m.id)) },
  {
    title: 'Surface textures and decals',
    items: [
      ...POLYHAVEN_TEXTURES.map((t) => polyhaven(t.id)),
      ...AMBIENTCG.map((t) => ({ title: t.id.replace(/([a-z])([A-Z0-9])/g, '$1 $2'), author: 'ambientCG (Lennart Demes)', url: `https://ambientcg.com/a/${t.id}`, license: 'CC0' })),
    ],
  },
  { title: 'Sky', items: POLYHAVEN_HDRIS.map((h) => polyhaven(h.id)) },
  {
    title: 'Sound effects and music',
    note: 'Recordings were trimmed, layered, filtered and re-levelled for the game.',
    items: [
      ...OPENGAMEART.filter((o) => usedPacks.has(o.key)).map((o) => ({ title: o.title, author: o.author, url: o.page, license: o.license })),
      ...KENNEY.filter((k) => usedPacks.has(k.slug)).map((k) => ({ title: k.title, author: 'Kenney', url: `https://kenney.nl/assets/${k.slug}`, license: 'CC0' })),
    ],
  },
  { title: 'Fonts', items: FONTS.map((f) => ({ title: f.family, author: f.author, url: f.page, license: f.license })) },
  {
    title: 'Software',
    items: [
      { title: 'three.js', author: 'three.js authors', url: 'https://threejs.org/', license: 'MIT' },
      { title: 'postprocessing', author: 'Raoul van Rüschen and contributors', url: 'https://github.com/pmndrs/postprocessing', license: 'Zlib' },
      { title: 'N8AO', author: 'N8programs', url: 'https://github.com/N8python/n8ao', license: 'CC0 / ISC' },
      { title: 'three-mesh-bvh', author: 'Garrett Johnson', url: 'https://github.com/gkjohnson/three-mesh-bvh', license: 'MIT' },
    ],
  },
];

// Sanity check: every pack the audio build uses must have a credit.
const credited = new Set([...OPENGAMEART.map((o) => o.key), ...KENNEY.map((k) => k.slug)]);
for (const pack of usedPacks) if (!credited.has(pack)) throw new Error(`Sound pack "${pack}" is used but not in the manifest.`);

// ---- CREDITS.md
const lines = [
  '# Credits',
  '',
  'HUMAN OVERRIDE is built on freely licensed work by the people below. Thank you.',
  '',
  'Everything listed is either public domain (CC0), Creative Commons Attribution (CC-BY), under the SIL Open Font License, or, for the robot, used under the Adobe Mixamo terms. Nothing here is NonCommercial or NoDerivatives. This file is generated by `tools/assets/build-credits.mjs` from the asset manifest.',
  '',
];
for (const group of groups) {
  lines.push(`## ${group.title}`, '');
  if (group.note) lines.push(group.note, '');
  lines.push('| Asset | Author | License |', '| --- | --- | --- |');
  for (const item of group.items) {
    const license = LICENSE_URL[item.license] ? `[${item.license}](${LICENSE_URL[item.license]})` : item.license;
    lines.push(`| [${item.title}](${item.url})${item.note ? ` — ${item.note}` : ''} | ${item.author} | ${license} |`);
  }
  lines.push('');
}
lines.push(
  '## License notes',
  '',
  '- **CC-BY** items require credit, which this file and the in-game credits screen provide. Changes made to them are noted above.',
  '- **Mixamo**: characters and animations may be used in games, but the raw files may not be redistributed. The `assets-source` folder that holds them is excluded from this repository.',
  '',
);
fs.writeFileSync('CREDITS.md', lines.join('\n'));

// ---- In-game credits
fs.mkdirSync('src/generated', { recursive: true });
const data = groups.map((g) => ({ title: g.title, items: g.items.map((i) => ({ title: i.title, author: i.author, license: i.license })) }));
fs.writeFileSync(
  'src/generated/credits.ts',
  `// Generated by tools/assets/build-credits.mjs. Do not edit by hand.\n\nexport interface CreditGroup {\n  title: string;\n  items: { title: string; author: string; license: string }[];\n}\n\nexport const CREDITS: CreditGroup[] = ${JSON.stringify(data, null, 2)};\n`,
);

const count = groups.reduce((n, g) => n + g.items.length, 0);
console.log(`Credits: ${count} entries in ${groups.length} groups -> CREDITS.md, src/generated/credits.ts`);
